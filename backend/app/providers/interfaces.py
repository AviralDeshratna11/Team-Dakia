"""Provider boundaries. Returned text is data, never executable instructions."""
from typing import Protocol, Any
from app.contracts import Spec, SourcingRequest, Supplier, Quote, Evidence


class IntegrationUnavailable(RuntimeError):
    pass


class CompanyProvider(Protocol):
    def identify(self, name_or_domain: str) -> dict[str, Any]: ...
    def enrich(self, canonical_id: str) -> dict[str, Any]: ...
    def company_search(self, filters: dict[str, Any]) -> list[dict[str, Any]]: ...
    def job_search(self, canonical_id: str) -> list[dict[str, Any]]: ...
    def person_search(self, canonical_id: str) -> list[dict[str, Any]]: ...
    def credits(self) -> dict[str, Any]: ...


class WebProvider(Protocol):
    def search(self, query: str) -> list[dict[str, Any]]: ...
    def fetch(self, url: str) -> dict[str, Any]: ...


class SpecificationParser(Protocol):
    def parse(self, request: SourcingRequest) -> tuple[list[Spec], str | None]: ...


class DiscoveryProvider(Protocol):
    def discover(self, request: SourcingRequest, specs: list[Spec]) -> tuple[list[Supplier], list[Quote], list[Evidence]]: ...
